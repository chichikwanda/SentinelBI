"""Build ``mappings/mitre.yaml`` from the official ATT&CK STIX data.

    python -m app.services.prescriptive.sync_mitre \
        data/raw/mitre-attack-enterprise/enterprise-attack.json

Only the mitigation ids that the rule files actually reference are written, each with the name
and URL taken from the STIX bundle. If a rule references an id that does not exist in the bundle
the script exits non-zero, so a mistyped or invented mitigation id cannot reach the UI.
Source: https://github.com/mitre-attack/attack-stix-data (enterprise-attack.json).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import yaml

from app.services.prescriptive.engine import MAPPINGS_DIR, load_rules


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    stix_path = Path(argv[1])
    raw = stix_path.read_bytes()
    bundle = json.loads(raw)

    mitigations: dict[str, dict[str, str]] = {}
    attack_version = "unknown"
    for obj in bundle["objects"]:
        if obj.get("type") == "x-mitre-collection":
            attack_version = obj.get("x_mitre_version", attack_version)
        if (
            obj.get("type") != "course-of-action"
            or obj.get("revoked")
            or obj.get("x_mitre_deprecated")
        ):
            continue
        for ref in obj.get("external_references", []):
            if ref.get("source_name") == "mitre-attack" and str(
                ref.get("external_id", "")
            ).startswith("M"):
                mitigations[ref["external_id"]] = {"title": obj["name"], "url": ref.get("url", "")}

    used = sorted({m for rule in load_rules() for act in rule.recommend for m in act.refs.mitre})
    missing = [m for m in used if m not in mitigations]
    if missing:
        print(
            f"ERROR: rules reference mitigations not found in the ATT&CK data: {missing}",
            file=sys.stderr,
        )
        return 1

    out = {
        "status": "verified-against-stix",
        "source": "https://github.com/mitre-attack/attack-stix-data (enterprise-attack.json)",
        "attack_version": attack_version,
        "stix_file_sha256": hashlib.sha256(raw).hexdigest(),
        "items": {m: mitigations[m] for m in used},
    }
    (MAPPINGS_DIR / "mitre.yaml").write_text(
        "# Generated by app.services.prescriptive.sync_mitre: do not edit by hand.\n"
        + yaml.safe_dump(out, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote mitre.yaml: {len(used)} mitigations (ATT&CK {attack_version})")
    for m in used:
        print(f"  {m}  {mitigations[m]['title']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
